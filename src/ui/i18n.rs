pub fn t(key: &'static str, locale: Locale) -> &'static str {
    match locale {
        Locale::En => translate_en(key),
        Locale::Fr => translate_fr(key).unwrap_or_else(|| translate_en(key)),
        Locale::Es => translate_es(key).unwrap_or_else(|| translate_en(key)),
        Locale::ZhCn => translate_zh(key).unwrap_or_else(|| translate_en(key)),
    }
}

pub fn has_translation(key: &'static str, locale: Locale) -> bool {
    match locale {
        Locale::En => translate_en(key) != key,
        Locale::Fr => translate_fr(key).is_some(),
        Locale::Es => translate_es(key).is_some(),
        Locale::ZhCn => translate_zh(key).is_some(),
    }
}

pub fn format_message(key: &'static str, locale: Locale, values: &[(&str, String)]) -> String {
    let mut message = t(key, locale).to_owned();
    for (name, value) in values {
        message = message.replace(&format!("{{{name}}}"), value);
    }
    message
}

